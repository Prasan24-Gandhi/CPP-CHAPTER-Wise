#include<iostream>
using namespace std;
int main()
{
    int num1 , num2 ;
    cout<<"Enter number 1 : \n"; // '<<' is called Insertion operator.
    cin>>num1;// '>>' is called Extraction operator.

    cout<<"Enter number 2 : \n";// '<<' is called Insertion operator.
    cin>>num2;// '>>' is called Extraction operator.

    cout<<"Sum of Number 1 and 2 is "<<num1 + num2;
    return 0;
}
